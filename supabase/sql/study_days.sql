-- Журнал учебных дней — источник правды для серии («streak»).
--
-- Зачем отдельная таблица. Раньше серия читалась из quiz_sessions, поэтому
-- считались только завершённые тесты: тот, кто каждый день делает карточки и
-- словарь, но не проходит тест, видел серию 0. Взять активность из
-- question_progress.updated_at нельзя — там хранится только ПОСЛЕДНИЙ отзыв по
-- каждой карточке, то есть более ранние дни занятий бесследно затираются.
--
-- День записывается в часовом поясе самого пользователя (его присылает браузер)
-- и хранится как обычная дата. Благодаря этому чтение серии не делает никаких
-- вычислений с поясами — просто шагает по календарю назад.
--
-- Применить один раз: Supabase Dashboard → SQL Editor → Run.
-- Скрипт идемпотентный, повторный запуск безопасен.

create table if not exists public.study_days (
  account_id uuid not null references public.accounts (id) on delete cascade,
  day        date not null,
  created_at timestamptz not null default now(),
  primary key (account_id, day)
);

-- Серия читает последние ~60 дней одного аккаунта: этому запросу нужен индекс
-- по (account_id, day). Первичный ключ его уже даёт, поэтому отдельный не
-- создаём — лишний индекс только замедлял бы вставку.

alter table public.study_days enable row level security;

-- Клиент в эту таблицу не ходит: пишет и читает только сервер бота через
-- service-key, который RLS обходит. Политик намеренно нет — при включённом RLS
-- и отсутствии политик любой анонимный доступ запрещён по умолчанию.

comment on table public.study_days is
  'Один день = одна строка. Заполняется при любом учебном действии: тест, карточки, словарь.';
comment on column public.study_days.day is
  'Календарный день в часовом поясе пользователя на момент занятия.';
